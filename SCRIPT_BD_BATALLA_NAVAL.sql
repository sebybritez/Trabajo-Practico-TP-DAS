CREATE DATABASE BATALLA_NAVAL;
GO
USE BATALLA_NAVAL;
GO

CREATE TABLE USUARIO (
    ID int NOT NULL PRIMARY KEY,
    NOMBRE varchar(50) NOT NULL,
    CONTRASENA varchar(50) NOT NULL,
    GANADAS int NOT NULL,
    PERDIDAS int NOT NULL,
    EMPATADAS int NOT NULL,
    SEGUNDOS_JUGADOS int NOT NULL
);

CREATE TABLE PARTIDA (
    ID int NOT NULL PRIMARY KEY,
    FECHA datetime NOT NULL,
    ID_JUGADOR1 int NOT NULL,
    ID_JUGADOR2 int NOT NULL,
    IMPACTOS_J1 int NOT NULL,
    IMPACTOS_J2 int NOT NULL,
    ID_GANADOR int NOT NULL,
    DURACION_SEGUNDOS int NOT NULL,
    ARCHIVO_XML varchar(300) NOT NULL
);

CREATE TABLE BITACORA (
    ID int NOT NULL PRIMARY KEY,
    FECHA datetime NOT NULL,
    ID_USUARIO int NOT NULL,
    EVENTO varchar(100) NOT NULL,
    DETALLE varchar(250) NOT NULL
);
GO

CREATE PROC USUARIO_INSERTAR
    @nom varchar(50),
    @pass varchar(50)
AS
BEGIN
    DECLARE @id int;
    SELECT @id = ISNULL(MAX(ID), 0) + 1 FROM USUARIO;

    INSERT INTO USUARIO (ID, NOMBRE, CONTRASENA, GANADAS, PERDIDAS, EMPATADAS, SEGUNDOS_JUGADOS)
    VALUES (@id, @nom, @pass, 0, 0, 0, 0);
END
GO

CREATE PROC USUARIO_LOGIN
    @nom varchar(50),
    @pass varchar(50)
AS
BEGIN
    SELECT ID, NOMBRE, CONTRASENA, GANADAS, PERDIDAS, EMPATADAS, SEGUNDOS_JUGADOS
    FROM USUARIO
    WHERE NOMBRE = @nom AND CONTRASENA = @pass;
END
GO

CREATE PROC USUARIO_LISTAR
AS
BEGIN
    SELECT ID, NOMBRE, CONTRASENA, GANADAS, PERDIDAS, EMPATADAS, SEGUNDOS_JUGADOS
    FROM USUARIO
    ORDER BY GANADAS DESC, NOMBRE ASC;
END
GO

CREATE PROC USUARIO_ACTUALIZAR_ESTADISTICAS
    @id int,
    @ganadas int,
    @perdidas int,
    @empatadas int,
    @segundos int
AS
BEGIN
    UPDATE USUARIO
    SET GANADAS = @ganadas,
        PERDIDAS = @perdidas,
        EMPATADAS = @empatadas,
        SEGUNDOS_JUGADOS = @segundos
    WHERE ID = @id;
END
GO

CREATE PROC BITACORA_INSERTAR
    @id_usuario int,
    @evento varchar(100),
    @detalle varchar(250)
AS
BEGIN
    DECLARE @id int;
    SELECT @id = ISNULL(MAX(ID), 0) + 1 FROM BITACORA;

    INSERT INTO BITACORA (ID, FECHA, ID_USUARIO, EVENTO, DETALLE)
    VALUES (@id, GETDATE(), @id_usuario, @evento, @detalle);
END
GO

CREATE PROC BITACORA_LISTAR
AS
BEGIN
    SELECT b.ID, b.FECHA, b.ID_USUARIO, u.NOMBRE AS USUARIO, b.EVENTO, b.DETALLE
    FROM BITACORA b
    INNER JOIN USUARIO u ON b.ID_USUARIO = u.ID
    ORDER BY b.ID DESC;
END
GO

CREATE PROC PARTIDA_INSERTAR
    @id_j1 int,
    @id_j2 int,
    @imp_j1 int,
    @imp_j2 int,
    @id_ganador int,
    @duracion int,
    @xml varchar(300)
AS
BEGIN
    DECLARE @id int;
    SELECT @id = ISNULL(MAX(ID), 0) + 1 FROM PARTIDA;

    INSERT INTO PARTIDA (ID, FECHA, ID_JUGADOR1, ID_JUGADOR2, IMPACTOS_J1, IMPACTOS_J2, ID_GANADOR, DURACION_SEGUNDOS, ARCHIVO_XML)
    VALUES (@id, GETDATE(), @id_j1, @id_j2, @imp_j1, @imp_j2, @id_ganador, @duracion, @xml);
END
GO

CREATE PROC PARTIDA_LISTAR
AS
BEGIN
    SELECT p.ID, p.FECHA, p.ID_JUGADOR1, u1.NOMBRE AS JUGADOR1,
           p.ID_JUGADOR2, u2.NOMBRE AS JUGADOR2,
           p.IMPACTOS_J1, p.IMPACTOS_J2, p.ID_GANADOR,
           CASE
               WHEN p.ID_GANADOR = 0 THEN 'Empate'
               WHEN p.ID_GANADOR = p.ID_JUGADOR1 THEN u1.NOMBRE
               ELSE u2.NOMBRE
           END AS GANADOR,
           p.DURACION_SEGUNDOS, p.ARCHIVO_XML
    FROM PARTIDA p
    INNER JOIN USUARIO u1 ON p.ID_JUGADOR1 = u1.ID
    INNER JOIN USUARIO u2 ON p.ID_JUGADOR2 = u2.ID
    ORDER BY p.ID DESC;
END
GO

